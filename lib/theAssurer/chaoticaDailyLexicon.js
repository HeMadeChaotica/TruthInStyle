function localCalendarParts(dateKey) {
  const match = String(dateKey || '').match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) return null;
  return { year: Number(match[1]), month: Number(match[2]), day: Number(match[3]) };
}

export function getChaoticaDailyWord(dateKey) {
  const parts = localCalendarParts(dateKey);
  if (!parts) return { word: CHAOTICA_DAILY_WORDS[0], definition: '', source: 'CHAOTICA DAILY LEXICON' };

  const dayOfYear = Math.floor((Date.UTC(parts.year, parts.month - 1, parts.day) - Date.UTC(parts.year, 0, 1)) / 86400000);
  return {
    word: CHAOTICA_DAILY_WORDS[dayOfYear],
    definition: '',
    source: 'CHAOTICA DAILY LEXICON',
  };
}

export function isLegacyMadeUpWord(value) {
  return LEGACY_MADE_UP_WORDS.has(String(value || '').trim().toUpperCase());
}
