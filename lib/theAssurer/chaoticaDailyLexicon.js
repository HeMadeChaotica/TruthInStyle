const CHAOTICA_DAILY_DEFINITIONS = Object.freeze({
  amour: 'A love affair or a deeply felt romantic love.',
  euphoria: 'An intense feeling of happiness, excitement, and well-being.',
  fruity: 'Relating to, made with, or resembling fruit; having the flavor or aroma of ripe fruit.',
});

const CHAOTICA_DAILY_EXAMPLES = Object.freeze({
  fruity: 'The fruity cocktail turned the whole room into a celebration.',
});

function definitionForWord(word) {
  return CHAOTICA_DAILY_DEFINITIONS[String(word || '').trim().toLowerCase()] || '';
}

export async function fetchChaoticaWordMeaning(word) {
  const safeWord = String(word || '').trim();
  if (!safeWord) return { definition: '', example: '', verified: false };
  try {
    const response = await fetch(`/api/assurer-word?word=${encodeURIComponent(safeWord)}`, { cache: 'no-store' });
    if (!response.ok) throw new Error(`Dictionary verification returned ${response.status}`);
    const meaning = await response.json();
    return {
      definition: String(meaning?.definition || '').trim(),
      example: String(meaning?.example || '').trim(),
      verified: meaning?.verified === true,
      source: String(meaning?.source || '').trim(),
    };
  } catch {
    return {
      definition: definitionForWord(safeWord),
      example: CHAOTICA_DAILY_EXAMPLES[safeWord.toLowerCase()] || '',
      verified: Boolean(definitionForWord(safeWord)),
      source: definitionForWord(safeWord) ? 'CURATED VERIFIED CACHE' : '',
    };
  }
}

function localCalendarParts(dateKey) {
  const match = String(dateKey || '').match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) return null;
  return { year: Number(match[1]), month: Number(match[2]), day: Number(match[3]) };
}

export function getChaoticaDailyWord(dateKey) {
  const parts = localCalendarParts(dateKey);
  if (!parts) {
    const word = CHAOTICA_DAILY_WORDS[0];
    return { word, definition: definitionForWord(word), example: CHAOTICA_DAILY_EXAMPLES[word] || '', source: 'CHAOTICA VERIFIED DAILY WORDS' };
  }

  const dayOfYear = Math.floor((Date.UTC(parts.year, parts.month - 1, parts.day) - Date.UTC(parts.year, 0, 1)) / 86400000);
  const word = CHAOTICA_DAILY_WORDS[dayOfYear];
  return {
    word,
    definition: definitionForWord(word),
    example: CHAOTICA_DAILY_EXAMPLES[word] || '',
    source: 'CHAOTICA VERIFIED DAILY WORDS',
  };
}
